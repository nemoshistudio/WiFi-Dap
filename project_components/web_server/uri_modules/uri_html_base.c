/* Security headers for the static UI (security review P2). The UI is a
 * single-file bundle: one inline module <script>, inline styles, a data:
 * favicon and the /ws.sharedworker.js worker. Network access is same-origin
 * HTTP/WS only, so everything else can be locked down. */
#define WEB_HTTP_CSP \
	"default-src 'self'; " \
	"script-src 'self' 'unsafe-inline' 'unsafe-eval'; " \
	"style-src 'self' 'unsafe-inline'; " \
	"img-src 'self' data: blob:; " \
	"font-src 'self' data:; " \
	"connect-src 'self' ws: wss:; " \
	"worker-src 'self' blob:; " \
	"object-src 'none'; " \
	"base-uri 'none'; " \
	"frame-ancestors 'none'; " \
	"form-action 'self'"

static void html_set_security_headers(httpd_req_t *req)
{
	httpd_resp_set_hdr(req, "X-Content-Type-Options", "nosniff");
	httpd_resp_set_hdr(req, "X-Frame-Options", "DENY");
	httpd_resp_set_hdr(req, "Referrer-Policy", "no-referrer");
}

/* Embedded gz assets from project_components/html (EMBED_FILES *.gz).
 * The symbol names are generated by the ESP-IDF embedding mechanism:
 *   index.html.gz         -> _binary_index_html_gz_start/_end
 *   ws.sharedworker.js.gz -> _binary_ws_sharedworker_js_gz_start/_end
 * Provenance (web version / protocol version / git commit) is recorded by the
 * Web UI build in project_components/html/version.txt; the gz files themselves
 * are embedded verbatim by project_components/html/CMakeLists.txt. */
extern const unsigned char index_html_gz_start[] asm("_binary_index_html_gz_start");
extern const unsigned char index_html_gz_end[] asm("_binary_index_html_gz_end");
extern const unsigned char ws_sharedworker_js_gz_start[] asm("_binary_ws_sharedworker_js_gz_start");
extern const unsigned char ws_sharedworker_js_gz_end[] asm("_binary_ws_sharedworker_js_gz_end");

static esp_err_t send_gzip_asset(httpd_req_t *req, const char *content_type,
                                 const unsigned char *start, const unsigned char *end)
{
	size_t file_size = (size_t) (end - start);

	html_set_security_headers(req);
	httpd_resp_set_hdr(req, "Content-Security-Policy", WEB_HTTP_CSP);
	httpd_resp_set_type(req, content_type);
	httpd_resp_set_hdr(req, "Content-Encoding", "gzip");
	/* Always revalidate the UI after a firmware update; the bundle name is
	 * stable ("/"), so a stale cache would mix old HTML with a new firmware. */
	httpd_resp_set_hdr(req, "Cache-Control", "no-cache");
#if defined(CONFIG_IDF_TARGET_ESP32C5)
	/* C5 real hardware (2026-10-26): a single 522 KiB httpd_resp_send() to a
	 * client that is slower than the Wi-Fi TX path blocked the whole response
	 * until the httpd send timeout (EAGAIN: "error in send : 11") and the page
	 * never loaded.  Sending the embedded UI in 16 KiB chunks keeps the socket
	 * writes bounded so a slow client drains between chunks instead of timing
	 * the whole transfer out.  Other targets keep the single-shot send. */
	{
		esp_err_t err = ESP_OK;
		size_t off = 0;
		const size_t chunk = 16 * 1024;
		while (off < file_size) {
			size_t n = (file_size - off > chunk) ? chunk : (file_size - off);
			err = httpd_resp_send_chunk(req, (const char *) start + off, n);
			if (err != ESP_OK) {
				return err;
			}
			off += n;
		}
		return httpd_resp_send_chunk(req, NULL, 0);
	}
#else
	return httpd_resp_send(req, (const char *) start, file_size);
#endif
}

#if defined(CONFIG_BIRDIEBOT_SSDP_ENABLE)
/* Slim build (H1): SSDP/UPnP is off by default, so /SSDP.xml is not served
 * (the request falls through to the SPA entry like any unknown path). */
static esp_err_t ssdp_xml_handler(httpd_req_t *req)
{
	char *buf = memory_pool_get(portMAX_DELAY);
	if (unlikely(buf == NULL)) {
		httpd_resp_set_status(req, "503 Busy");
		return httpd_resp_send(req, NULL, 0);
	}

	int ret = ssdp_get_schema_str(buf, memory_pool_get_buf_size());
	esp_err_t err;
	if (unlikely(ret <= 0)) {
		err = httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR,
		                          "SSDP schema unavailable");
	} else {
		html_set_security_headers(req);
		httpd_resp_set_type(req, "text/xml");
		err = httpd_resp_send(req, buf, strlen(buf));
	}
	memory_pool_put(buf);
	return err;
}
#endif /* CONFIG_BIRDIEBOT_SSDP_ENABLE */

/**
 * @brief GET "/" handler: serves the embedded Web UI + a couple of static
 *        companion resources (docs/protocol.md §1):
 *          /            -> index.html.gz (gzip)
 *          /ws.*        -> ws.sharedworker.js.gz (gzip)
 *          /SSDP.xml    -> SSDP device description XML (full-feature build only;
 *                          CONFIG_BIRDIEBOT_SSDP_ENABLE, off in the slim build)
 *
 * The cheap first-word "hash" keeps /ws.* and /SSDP.xml dispatch constant time
 * on the single httpd task (same trick as the upstream C tree).
 */
static esp_err_t html_base_get_handler(httpd_req_t *req)
{
	httpd_resp_set_hdr(req, "Connection", "close");

	/* URL-aware prefix match instead of a 4-byte word read (security review
	 * P3: short URIs like "/" must not read past their NUL terminator). */
	if (strncmp(req->uri, "/ws.", 4) == 0) {
		return send_gzip_asset(req, "text/javascript",
		                       ws_sharedworker_js_gz_start, ws_sharedworker_js_gz_end);
	}
#if defined(CONFIG_BIRDIEBOT_SSDP_ENABLE)
	if (strncmp(req->uri, "/SSDP.xml", 9) == 0) {
		return ssdp_xml_handler(req);
	}
#endif

	/* Everything else falls back to the SPA entry page (the client-side
	 * router handles unknown paths). */
	return send_gzip_asset(req, "text/html",
	                       index_html_gz_start, index_html_gz_end);
}

/**
 * REGISTER MODULE
 * */

static const httpd_uri_t hello = {
	.uri       = "/",
	.method    = HTTP_GET,
	.handler   = html_base_get_handler,
};

static int URI_HTML_BASE_INIT(const httpd_uri_t **uri_conf) {
	*uri_conf = &hello;
	return 0;
}

static int URI_HTML_BASE_EXIT(const httpd_uri_t **uri_conf) {
	*uri_conf = &hello;
	return 0;
}

WEB_URI_MODULE_REGISTER(0x90, URI_HTML_BASE_INIT, URI_HTML_BASE_EXIT);
